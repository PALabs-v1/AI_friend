"""Phase 5 report generators. Everything here is derived from the index and the claims table.

Nothing in these reports is typed by hand: re-running `audit` after a change
regenerates them, and a claim that went stale shows up as stale.
"""

from __future__ import annotations

import re
import sqlite3
from collections import Counter, defaultdict

from . import structure

DEBT_CATEGORIES = [
    "correctness",
    "reliability",
    "performance",
    "security",
    "maintainability",
    "integration",
    "testing",
    "architecture",
]
SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
IGNORED_AREAS = (
    "/tests/",
    "tests/",
    "tools/",
    "docs/",
    "backend/tools/",
    "scripts/",
    "backend/scripts/",
    "benchmarks/",
    "evals/",
    "backend/evals/",
)


def _component(path: str) -> str:
    parts = path.split("/")
    if (
        parts[0] == "backend"
        and len(parts) > 2
        and parts[1] in ("app", "crates", "evals", "tests", "tools", "scripts")
    ):
        return (
            "/".join(parts[:3])
            if parts[1] in ("app", "crates") and len(parts) > 3
            else "/".join(parts[:2])
        )
    return parts[0] if len(parts) > 1 else "(root)"


def _is_prod(path: str) -> bool:
    return not any(m in path for m in IGNORED_AREAS) and not path.rsplit("/", 1)[
        -1
    ].startswith("test_")


def _table(headers, rows) -> str:
    out = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return "\n".join(out)


def architecture_map(conn: sqlite3.Connection, revision: str) -> str:
    st = structure.stats(conn)
    L = [
        "# Architecture map (generated)\n",
        (
            f"Generated by `python -m tools.repo_intel audit` from the structural index at revision `{revision}`. "
            "Do not edit by hand; regenerate. Edge confidence tiers: proven (syntax tree resolved), lexical (Rust/JS pattern match), "
            "inferred (name match only), unresolved (dynamic or ambiguous), external (outside the repo).\n"
        ),
        (
            f"Index: {st['parsed']} of {st['in_scope']} in-scope files parsed; {sum(st['symbols_by_kind'].values()):,} symbols; "
            f"{sum(st['edges_by_kind_confidence'].values()):,} edges.\n"
        ),
    ]
    # --- components
    comp: dict[str, dict] = defaultdict(lambda: {"files": 0, "symbols": 0, "tested": 0})
    for r in conn.execute(
        "SELECT f.path, f.language, (SELECT COUNT(*) FROM symbols s WHERE s.file_id=f.id AND s.kind IN ('function','method','class','fn','struct','enum','trait')) n "
        "FROM files f WHERE f.in_scope=1 AND f.present=1 AND f.language IN ('python','rust','javascript','typescript')"
    ):
        c = comp[_component(r["path"])]
        c["files"] += 1
        c["symbols"] += r["n"]
    tested = {
        r[0]
        for r in conn.execute(
            "SELECT DISTINCT t.path FROM edges e JOIN files t ON t.id=e.dst_file_id WHERE e.kind='TEST_VALIDATES'"
        )
    }
    for p in tested:
        comp[_component(p)]["tested"] += 1
    L.append("## 1. Components (code files)\n")
    L.append(
        _table(
            ["Component", "Code files", "Symbols", "Files imported by a test"],
            [
                (k, v["files"], v["symbols"], v["tested"])
                for k, v in sorted(comp.items(), key=lambda kv: -kv[1]["files"])
            ],
        )
    )
    # --- package dependency matrix
    pk: Counter = Counter()
    for r in conn.execute(
        "SELECT f.path src, t.path dst FROM edges e JOIN files f ON f.id=e.file_id JOIN files t ON t.id=e.dst_file_id "
        "WHERE e.kind='IMPORTS' AND e.confidence='proven' AND f.path LIKE 'backend/app/%' AND t.path LIKE 'backend/app/%'"
    ):
        a, b = _component(r["src"]), _component(r["dst"])
        if a != b:
            pk[(a, b)] += 1
    L.append(
        "\n## 2. Import dependencies between `backend/app` packages (proven edges)\n"
    )
    L.append(
        _table(
            ["From", "To", "Imports"], [(a, b, n) for (a, b), n in pk.most_common(40)]
        )
    )
    L.append("\n```mermaid\nflowchart LR")
    for (a, b), n in pk.most_common(22):
        L.append(
            f'  {_mid(a)}["{a.replace("backend/app/", "")}"] -->|{n}| {_mid(b)}["{b.replace("backend/app/", "")}"]'
        )
    L.append("```")
    # --- entrypoints
    L.append("\n## 3. Runtime entrypoints\n")
    rows = [
        (r["path"], r["line"])
        for r in conn.execute(
            "SELECT f.path, s.line FROM symbols s JOIN files f ON f.id=s.file_id WHERE s.kind='entrypoint' ORDER BY f.path"
        )
    ]
    prod = [(p, l) for p, l in rows if _is_prod(p)]
    L.append(
        f"{len(rows)} modules guard a `__main__` block; {len(prod)} are outside tests, tools, scripts and evals:\n"
    )
    L.append(_table(["File", "Line"], prod))
    rust = conn.execute(
        "SELECT f.path, s.line FROM symbols s JOIN files f ON f.id=s.file_id WHERE s.kind='fn' AND s.name='main' AND f.language='rust'"
    ).fetchall()
    L.append(
        "\nRust binaries (`fn main`): "
        + ", ".join(f"`{r['path']}:{r['line']}`" for r in rust)
    )
    routes = conn.execute(
        "SELECT f.path, e.dst, e.line FROM edges e JOIN files f ON f.id=e.file_id WHERE e.kind='REGISTERS_ROUTE' ORDER BY f.path, e.line"
    ).fetchall()
    L.append(f"\nHTTP/WebSocket routes registered by decorator ({len(routes)}):\n")
    L.append(
        _table(
            ["Route", "File:line"],
            [(r["dst"], f"{r['path']}:{r['line']}") for r in routes],
        )
    )
    # --- NATS matrix
    m = structure.subject_matrix(conn)
    L.append(
        "\n## 4. NATS subject matrix (production code only; tests, tools, scripts excluded)\n"
    )
    rows, orphan_pub, orphan_sub = [], [], []
    for subj, d in sorted(m.items()):
        if subj.startswith("<"):
            continue
        pubs = [x for x in d["PUBLISHES"] if _is_prod(x[0])]
        subs = [x for x in d["SUBSCRIBES"] if _is_prod(x[0])]
        if not pubs and not subs:
            continue
        langs = lambda xs: (
            "/".join(sorted({"rs" if p.endswith(".rs") else "py" for p, *_ in xs}))
            or "-"
        )
        conf = sorted({x[3] for x in pubs + subs})
        rows.append(
            (
                subj,
                ", ".join(sorted({_short(p) for p, *_ in pubs})) or "NONE",
                ", ".join(sorted({_short(p) for p, *_ in subs})) or "NONE",
                f"{langs(pubs)} -> {langs(subs)}",
                "/".join(conf),
            )
        )
        if not subs:
            orphan_pub.append(subj)
        if not pubs:
            orphan_sub.append(subj)
    L.append(
        _table(
            ["Subject", "Published by", "Subscribed by", "Languages", "Confidence"],
            rows,
        )
    )
    L.append(
        f"\nPublished with no production subscriber found ({len(orphan_pub)}): "
        + (", ".join(f"`{s}`" for s in orphan_pub) or "none")
    )
    L.append(
        f"\nSubscribed with no production publisher found ({len(orphan_sub)}): "
        + (", ".join(f"`{s}`" for s in orphan_sub) or "none")
    )
    L.append(
        "\nA subject listed as orphaned may still be wired through a forwarder, a wildcard, or a call whose subject the "
        "extractor could not read. Subjects that stayed unresolved: "
        + str(
            conn.execute(
                "SELECT COUNT(*) FROM edges WHERE kind IN ('PUBLISHES','SUBSCRIBES') AND confidence='unresolved'"
            ).fetchone()[0]
        )
        + " call sites."
    )
    L.append("\n```mermaid\nflowchart LR")
    agents = defaultdict(lambda: {"pub": set(), "sub": set()})
    for subj, d in m.items():
        if subj.startswith("<"):
            continue
        for p, *_ in d["PUBLISHES"]:
            if _is_prod(p):
                agents[_short(p)]["pub"].add(subj)
        for p, *_ in d["SUBSCRIBES"]:
            if _is_prod(p):
                agents[_short(p)]["sub"].add(subj)
    key = [
        s
        for s, d in m.items()
        if not s.startswith("<")
        and any(_is_prod(x[0]) for x in d["PUBLISHES"])
        and any(_is_prod(x[0]) for x in d["SUBSCRIBES"])
    ]
    for a, d in sorted(agents.items()):
        for s in sorted(d["pub"] & set(key)):
            L.append(f'  {_mid(a)}["{a}"] -->|{s}| {_mid("bus")}(("NATS"))')
        for s in sorted(d["sub"] & set(key)):
            L.append(f"  {_mid('bus')} -->|{s}| {_mid(a)}")
    L.append("```\n")
    # --- storage
    L.append("## 5. Persistence touched by code (SQL strings, inferred)\n")
    defined = {}
    for r in conn.execute(
        "SELECT s.name, f.path FROM symbols s JOIN files f ON f.id=s.file_id WHERE s.kind='table' ORDER BY f.path"
    ):
        if _is_prod(r["path"]):
            defined.setdefault(r["name"], _short(r["path"]))
    rows = conn.execute(
        "SELECT e.dst t, e.kind k, f.path FROM edges e JOIN files f ON f.id=e.file_id WHERE e.kind IN ('READS_STORAGE','WRITES_STORAGE')"
    ).fetchall()
    tab: dict[str, dict[str, set]] = defaultdict(lambda: {"R": set(), "W": set()})
    for r in rows:
        name = r["t"][6:]
        if _is_prod(r["path"]) and name in defined:
            tab[name]["W" if r["k"] == "WRITES_STORAGE" else "R"].add(_short(r["path"]))
    L.append(
        "Only tables with a CREATE TABLE statement somewhere in production code are listed (SQL in prose strings produced false names before this filter).\n"
    )
    L.append(
        _table(
            ["Table", "Created in", "Written by", "Read by"],
            [
                (
                    t,
                    defined[t],
                    ", ".join(sorted(d["W"])) or "-",
                    ", ".join(sorted(d["R"])) or "-",
                )
                for t, d in sorted(tab.items())
            ],
        )
    )
    # --- env
    L.append(
        "\n## 6. Environment variables read directly (`os.getenv`, `os.environ`)\n"
    )
    env = Counter()
    where = defaultdict(set)
    for r in conn.execute(
        "SELECT e.dst v, f.path FROM edges e JOIN files f ON f.id=e.file_id WHERE e.kind='READS_ENV'"
    ):
        env[r["v"]] += 1
        where[r["v"]].add(_short(r["path"]))
    L.append(
        f"{len(env)} variables. Settings read through `app/config.py` fields are not listed here.\n"
    )
    L.append(
        _table(
            ["Variable", "Reads", "Files"],
            [(v, n, ", ".join(sorted(where[v]))[:90]) for v, n in env.most_common(40)],
        )
    )
    # --- dynamic
    L.append("\n## 7. Dynamic constructs the index cannot resolve\n")
    L.append("Absence of a static reference near these is not evidence of non-use.\n")
    dyn = conn.execute(
        "SELECT f.path, e.line, e.dst, e.evidence FROM edges e JOIN files f ON f.id=e.file_id WHERE e.kind='DYNAMIC' ORDER BY f.path, e.line"
    ).fetchall()
    L.append(
        _table(
            ["Where", "Kind", "Code"],
            [
                (f"{r['path']}:{r['line']}", r["dst"], r["evidence"][:70])
                for r in dyn
                if _is_prod(r["path"])
            ],
        )
    )
    L.append(
        f"\n({len(dyn) - sum(1 for r in dyn if _is_prod(r['path']))} more in tests, tools and scripts.)"
    )
    # --- test association
    L.append("\n## 8. Production modules no test imports\n")
    allp = conn.execute(
        "SELECT f.path, (SELECT COUNT(*) FROM symbols s WHERE s.file_id=f.id AND s.kind IN ('function','method','class')) n FROM files f "
        "WHERE f.in_scope=1 AND f.present=1 AND f.language='python' AND f.path LIKE 'backend/app/%' AND f.path NOT LIKE '%/__init__.py' ORDER BY f.path"
    ).fetchall()
    untested = [r for r in allp if r["path"] not in tested]
    L.append(
        f"{len(untested)} of {len(allp)} `backend/app` modules are not imported by any test (importing is necessary, not sufficient, for coverage):\n"
    )
    L.append(
        _table(["Module", "Functions/classes"], [(r["path"], r["n"]) for r in untested])
    )
    # --- doc drift
    L.append("\n## 9. Documents that cite paths which do not exist\n")
    drift = Counter()
    ex: dict[str, list] = defaultdict(list)
    for r in conn.execute(
        "SELECT f.path doc, e.dst, e.line, e.kind FROM edges e JOIN files f ON f.id=e.file_id WHERE e.kind IN ('DOC_MENTIONS','DOC_LINKS') AND e.confidence='unresolved'"
    ):
        drift[r["doc"]] += 1
        if len(ex[r["doc"]]) < 2:
            ex[r["doc"]].append(f"{r['dst']}:{r['line']}")
    L.append(
        f"{sum(drift.values())} unresolved citations in {len(drift)} documents (top 30):\n"
    )
    L.append(
        _table(
            ["Document", "Dead citations", "Examples"],
            [(d, n, "; ".join(ex[d])) for d, n in drift.most_common(30)],
        )
    )
    return "\n".join(L) + "\n"


def _mid(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", s)


def _short(path: str) -> str:
    if path.startswith("backend/app/"):
        return path[len("backend/app/") :]
    if path.startswith("backend/crates/"):
        return path[len("backend/crates/") :].replace("/src/", "/")
    return path


def discrepancy_report(conn: sqlite3.Connection) -> str:
    L = [
        "# Architecture discrepancy report (generated from the claims ledger)\n",
        (
            "Each row is a claim recorded with evidence. Status comes from a deterministic check run against the current code, "
            "and `verified` requires an independent reader. Classification is the verdict on the earlier document's conclusion: "
            "still supported, superseded, contradicted, incomplete, unverifiable. Historical documents are not edited; this report is the audit trail.\n"
        ),
    ]
    rows = conn.execute(
        "SELECT * FROM claims WHERE classification!='n/a' ORDER BY classification, severity, id"
    ).fetchall()
    counts = Counter(r["classification"] for r in rows)
    L.append(
        "Summary: "
        + ", ".join(f"{k} {v}" for k, v in sorted(counts.items()))
        + f"; status mix {dict(Counter(r['status'] for r in rows))}\n"
    )
    for cls in [
        "contradicted",
        "superseded",
        "incomplete",
        "unverifiable",
        "still_supported",
    ]:
        sub = [r for r in rows if r["classification"] == cls]
        if not sub:
            continue
        L.append(f"\n## {cls.replace('_', ' ').capitalize()} ({len(sub)})\n")
        L.append(
            _table(
                ["#", "Source", "Conclusion", "Status", "Evidence from current code"],
                [
                    (
                        r["id"],
                        r["source"],
                        r["text"],
                        r["status"],
                        (r["status_detail"] or "")[:140],
                    )
                    for r in sub
                ],
            )
        )
    return "\n".join(L) + "\n"


def debt_registry(conn: sqlite3.Connection) -> str:
    L = [
        "# Technical debt and defect registry (generated from the claims ledger)\n",
        (
            "Recorded and prioritised, not fixed. `status` is what the checks say about the finding against the current code: "
            "supported means the defect or gap is confirmed present, refuted means the finding did not hold.\n"
        ),
    ]
    rows = [
        r
        for r in conn.execute(
            "SELECT * FROM claims WHERE kind LIKE 'debt:%' ORDER BY id"
        )
    ]
    rows.sort(key=lambda r: (SEV_ORDER.get(r["severity"], 9), r["id"]))
    L.append(
        "Findings by category: "
        + ", ".join(
            f"{c} {sum(1 for r in rows if r['kind'] == 'debt:' + c)}"
            for c in DEBT_CATEGORIES
        )
        + "\n"
    )
    for c in DEBT_CATEGORIES:
        sub = [r for r in rows if r["kind"] == "debt:" + c]
        if sub:
            L.append(f"\n## {c.capitalize()}\n")
            L.append(
                _table(
                    ["#", "Severity", "Finding", "Status", "Evidence"],
                    [
                        (
                            r["id"],
                            r["severity"],
                            r["text"],
                            r["status"],
                            (r["status_detail"] or "")[:130],
                        )
                        for r in sub
                    ],
                )
            )
    return "\n".join(L) + "\n"


def note_quality(conn: sqlite3.Connection) -> str:
    """Deterministic cross-check of the reading notes against the structural index.

    This is NOT the independent second reader (that is the `verified` stage). It measures two things a script can:
    do the paths a note says the file depends on exist, and how many of the file's top-level definitions the note names.
    """
    import json

    present = {r[0] for r in conn.execute("SELECT path FROM files WHERE present=1")}
    notes = conn.execute(
        "SELECT f.id, f.path, f.language, n.symbols, n.depends_on FROM files f JOIN notes n ON n.file_id=f.id AND n.sha256=f.sha256 "
        "WHERE f.in_scope=1 AND f.present=1 AND n.id=(SELECT MAX(id) FROM notes WHERE file_id=f.id AND sha256=f.sha256)"
    ).fetchall()
    dep_total = dep_bad = dep_suffix = 0
    bad: list[tuple[str, str]] = []
    recalls: list[tuple[float, str, int, int]] = []
    for n in notes:
        for d in json.loads(n["depends_on"] or "[]"):
            dep_total += 1
            dd = d.lstrip("/").removeprefix("./")
            if dd in present or any(
                p.startswith(dd.rstrip("/") + "/") for p in present
            ):
                continue
            hits = [p for p in present if p.endswith("/" + dd)]
            if len(hits) == 1:
                dep_suffix += 1
            else:
                dep_bad += 1
                bad.append((n["path"], d + (" (ambiguous)" if hits else "")))
        if n["language"] in ("python", "rust"):
            top = [
                r[0]
                for r in conn.execute(
                    "SELECT name FROM symbols WHERE file_id=? AND kind IN ('class','function','struct','enum','trait','fn') AND qualname NOT LIKE '%.%' AND qualname NOT LIKE '%::%' AND name NOT LIKE '\\_%' ESCAPE '\\'",
                    (n["id"],),
                )
            ]
            if len(top) >= 3:
                listed = set(json.loads(n["symbols"] or "[]"))
                hit = sum(1 for t in top if t in listed)
                recalls.append((hit / len(top), n["path"], hit, len(top)))
    L = [
        "# Reading-note quality (deterministic cross-check)\n",
        "Not the independent second reader. It checks what a script can check about the notes written during the read phase.\n",
        f"- Notes cross-checked: {len(notes)}",
        f"- `depends_on` paths that resolve exactly: {dep_total - dep_bad - dep_suffix} of {dep_total}; resolve only as a unique path suffix (written short): {dep_suffix}; do not resolve: {dep_bad} ({100 * dep_bad / max(dep_total, 1):.1f}%)",
    ]
    if recalls:
        mean = sum(r[0] for r in recalls) / len(recalls)
        L.append(
            f"- Code files with 3 or more public top-level definitions: {len(recalls)}; mean share of those definitions the note names: {100 * mean:.1f}%"
        )
        L.append(
            f"- Files whose note names none of their public definitions: {sum(1 for r in recalls if r[0] == 0)}"
        )
    if bad:
        L.append("\n## Notes citing paths that do not exist\n")
        L.append(_table(["Note for", "Cites"], bad[:40]))
    if recalls:
        L.append("\n## Lowest definition recall (largest gaps first)\n")
        L.append(
            _table(
                ["File", "Named", "Public definitions", "Recall"],
                [(p, h, t, f"{100 * r:.0f}%") for r, p, h, t in sorted(recalls)[:25]],
            )
        )
    return "\n".join(L) + "\n"
